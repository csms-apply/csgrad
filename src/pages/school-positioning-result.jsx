function AdviceSection({ advice, t }) {
  if (!advice || typeof advice !== 'string' || !advice.trim()) return null;
  const paragraphs = advice
    .split(/\n\s*\n+/)
    .map((p) => p.trim())
    .filter((p) => p.length > 0);
  if (paragraphs.length === 0) return null;
  return (
    <div className={styles.adviceCard}>
      <p className={styles.adviceTitle}>{t.adviceTitle}</p>
      <div className={styles.adviceProse}>
        {paragraphs.map((p, i) => (
          <p key={i} className={styles.adviceParagraph}>{p}</p>
        ))}
      </div>
    </div>
  );
}

export function Bucket({ items, title, subtitle, variantClass, locale, t }) {
  const list = Array.isArray(items) ? items : [];
  return (
    <div className={`${styles.bucket} ${variantClass}`}>
      <div className={styles.bucketHeader}>
        <h3 className={styles.bucketTitle}>
          {title}
          {subtitle && subtitle !== title && <span className={styles.bucketSubtitle}>{subtitle}</span>}
        </h3>
        <span className={styles.bucketCount}>{list.length}</span>
      </div>
      <div className={styles.schoolList}>
        {list.length === 0 ? (
          <div className={styles.emptyBucket}>{t.emptyBucket}</div>
        ) : (
          list.map((s, i) => (
            <SchoolCard key={s.id || s.slug || i} school={s} locale={locale} t={t} />
          ))
        )}
      </div>
    </div>
  );
}

