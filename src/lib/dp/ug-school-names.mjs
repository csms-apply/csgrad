export function ugSchoolLabelsFor(locale) {
  return String(locale || '').startsWith('zh') ? null : UG_SCHOOL_EN;
}

export function displayUgSchool(name, labels) {
  const key = String(name || '').trim();
  return (labels && labels[key]) || name;
}
