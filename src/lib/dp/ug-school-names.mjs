export const UG_SCHOOL_NAMES = [...CHINESE_NAMED.map(([name]) => name), ...OVERSEAS];
export const UG_SCHOOL_EN = Object.fromEntries(CHINESE_NAMED);
const KNOWN = new Set(UG_SCHOOL_NAMES);
const BY_LOWER = new Map(UG_SCHOOL_NAMES.map((name) => [name.toLowerCase(), name]));

export function isKnownUgSchool(name) {
  return KNOWN.has(String(name || '').trim());
}

// Map an alias or differently-cased spelling to the stored name; unknown
// names are returned trimmed and otherwise unchanged.
export function normalizeUgSchool(name) {
  const key = String(name || '').trim();
  const lower = key.toLowerCase();
  return BY_LOWER.get(lower) || ALIASES[lower] || key;
}

export function ugSchoolLabelsFor(locale) {
  return String(locale || '').startsWith('zh') ? null : UG_SCHOOL_EN;
}

export function displayUgSchool(name, labels) {
  const key = String(name || '').trim();
  return (labels && labels[key]) || name;
}

// Schools matching a typed query by stored name, English name or alias.
export function searchUgSchools(query, limit = 8) {
  const q = String(query || '').trim().toLowerCase();
  if (!q) return [];
  const hits = [];
  const aliasHit = ALIASES[q];
  if (aliasHit) hits.push(aliasHit);
  for (const name of UG_SCHOOL_NAMES) {
    if (hits.length >= limit) break;
    if (hits.includes(name)) continue;
    const en = UG_SCHOOL_EN[name];
    if (name.toLowerCase().includes(q) || (en && en.toLowerCase().includes(q))) hits.push(name);
  }
  return hits;
}
